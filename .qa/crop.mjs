import { createRequire } from 'node:module';
import { join } from 'node:path';
import { readFileSync } from 'node:fs';
const runtime = join(process.env.HOME, '.local/share/omgithub-playwright');
const require = createRequire(join(runtime, 'package.json'));
const { chromium } = require('playwright');
const [src, x, y, w, h, scale = '2', out = '.qa/shots/crop.png'] = process.argv.slice(2);
const S = Number(scale);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: Math.round(Number(w) * S), height: Math.round(Number(h) * S) }, deviceScaleFactor: 1 });
const b64 = readFileSync(src).toString('base64');
await page.setContent(`<body style="margin:0;background:#000;overflow:hidden"><img src="data:image/png;base64,${b64}" style="position:absolute;left:${-Number(x) * S}px;top:${-Number(y) * S}px;transform-origin:0 0;transform:scale(${S});image-rendering:pixelated">`);
await page.waitForTimeout(250);
await page.screenshot({ path: out });
await browser.close();

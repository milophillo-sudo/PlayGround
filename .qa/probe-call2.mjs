import { createRequire } from 'node:module';
import { join } from 'node:path';
const runtime = join(process.env.HOME, '.local/share/omgithub-playwright');
const require = createRequire(join(runtime, 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
page.on('console', (m) => console.log('CONSOLE', m.text()));
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await page.goto('http://127.0.0.1:4173/index.html', { waitUntil: 'load' });
await page.waitForTimeout(1500);
console.log('mode0', await page.evaluate(() => ({ mode: window.__lastCan.mode, hasGame: !!window.__lastCan.game })));
await page.evaluate(() => window.__lastCan.startGame());
await page.waitForTimeout(1500);
console.log('s1', await page.evaluate(() => { const g = window.__lastCan.game; return { mode: window.__lastCan.mode, same: g === window.__lastCan.game, running: g.running, paused: g.paused, phase: g.phase, tasks: g.tasks.length, time: g.time }; }));
await page.evaluate(() => { const g = window.__lastCan.game; g.__ref = g; g.chaseSequence(); });
await page.waitForTimeout(600);
console.log('s2', await page.evaluate(() => { const g = window.__lastCan.game; return { mode: window.__lastCan.mode, same: g === g.__ref, running: g.running, paused: g.paused, phase: g.phase, tasks: g.tasks.length, time: g.time }; }));
await page.waitForTimeout(2500);
console.log('s3', await page.evaluate(() => { const g = window.__lastCan.game; return { mode: window.__lastCan.mode, same: g === g.__ref, running: g.running, paused: g.paused, phase: g.phase, tasks: g.tasks.length, time: g.time, knife: !!g.threatKnife }; }));
await browser.close();

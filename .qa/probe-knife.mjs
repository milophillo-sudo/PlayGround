import { createRequire } from 'node:module';
import { join } from 'node:path';
const runtime = join(process.env.HOME, '.local/share/omgithub-playwright');
const require = createRequire(join(runtime, 'package.json'));
const { chromium } = require('playwright');
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 960, height: 540 } });
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await page.goto('http://127.0.0.1:4173/index.html', { waitUntil: 'load' });
await page.waitForTimeout(1500);
await page.evaluate(() => window.__lastCan.startGame());
await page.waitForTimeout(1500);
console.log('pre', await page.evaluate(() => ({ phase: window.__lastCan.game.phase, disposed: window.__lastCan.game.disposed })));
await page.evaluate(() => { window.__lastCan.game.chaseSequence().catch(e => console.log('CHASE ERR', e && e.message, e && e.stack)); });
await page.evaluate(() => window.__lastCan.advance(2.5));
await page.waitForTimeout(300);
console.log('post', await page.evaluate(() => ({ phase: window.__lastCan.game.phase, knife: !!window.__lastCan.game.threatKnife })));
console.log(await page.evaluate(async () => {
  const THREE = await import('three');
  const g = window.__lastCan.game;
  const k = g.threatKnife;
  const p = new THREE.Vector3();
  k.getWorldPosition(p);
  const ndc = p.clone().project(g.camera);
  const cam = g.camera;
  const rc = new THREE.Raycaster();
  rc.setFromCamera(new THREE.Vector2(ndc.x, ndc.y), cam);
  const hits = rc.intersectObjects(g.scene.children, true).slice(0, 3).map(h => ({ vis: h.object.visible, geo: h.object.geometry?.type, d: +h.distance.toFixed(2), parent: h.object.parent?.type }));
  return { pos: p.toArray().map(v => +v.toFixed(2)), screen: [(ndc.x * 0.5 + 0.5) * 960, (-ndc.y * 0.5 + 0.5) * 540].map(v => +v.toFixed(0)), hits, knifeChildren: k.children.length, visible: k.visible };
}));
await page.screenshot({ path: '.qa/shots/knife.png', timeout: 120000 });
await browser.close();

function assignLanes(track, song, sec, candidates, context) {
  if (!candidates.length) return [];
  const keys = sec.keys;
  const active = ACTIVE[keys];
  const figures = FIGURES[keys];
  const { bar, offset } = tempoFor(song, sec);
  const taps = [];
  const lastUse = new Map();
  const minGap = keys <= 2 ? 0.13 : 0.085;
  let lastLane = context.lastLane;
  let lastT = context.lastT;
  const barCounts = new Map();

  if (keys > 1 && !active.includes(lastLane)) {
    lastLane = active[Math.floor(keys / 2) - (keys % 2 === 0 ? 1 : 0)];
  }

  for (const cand of candidates) {
    const barNo = Math.floor((cand.t - offset) / bar + 1e-6);
    const barInPhrase = ((barNo % 4) + 4) % 4;
    const phrase = Math.floor(barNo / 4);
    const base = Math.floor((track.seed + sec.start * 13 + phrase * 5) % figures.length);
    const figure = figures[(base + [0, 0, 1, 3][barInPhrase]) % figures.length];
    const noteIndex = barCounts.get(barNo) || 0;
    barCounts.set(barNo, noteIndex + 1);

    let lane = -1;
    const maxJump = cand.strong ? Math.ceil(keys * 0.7) : Math.ceil(keys * 0.46);
    for (let attempt = 0; attempt < keys + 2; attempt++) {
      const pos = figure[(noteIndex + attempt) % figure.length];
      const next = lanePos(keys, pos);
      const tooSoon = cand.t - (lastUse.get(next) ?? -99) < minGap;
      const sameFast = next === lastLane && cand.t - lastT < (cand.strong ? 0.16 : 0.22);
      const jump = Math.abs(next - lastLane);
      const tooFar = keys > 2 && lastT > -90 && jump > maxJump + attempt;
      if (!tooSoon && !sameFast && !tooFar) {
        lane = next;
        break;
      }
    }
    if (lane < 0) {
      const ordered = [...active].sort((a, b) => Math.abs(a - lastLane) - Math.abs(b - lastLane));
      lane = ordered.find((l) => cand.t - (lastUse.get(l) ?? -99) >= minGap) ?? ordered[0];
    }

    taps.push({ t: cand.t, lane, step: cand.step, strong: cand.strong, barNo });
    lastUse.set(lane, cand.t);
    lastLane = lane;
    lastT = cand.t;
  }

  // Chords are phrase accents, not a default texture.
  if (keys >= 4 && sec.energy > 0.74) {
    let chords = 0;
    for (let i = 0; i < taps.length && chords < 2; i++) {
      const note = taps[i];
      if (note.chord || note.step !== 0) continue;
      const barInPhrase = ((note.barNo % 4) + 4) % 4;
      if (barInPhrase !== 0) continue;
      const pos = active.indexOf(note.lane);
      const options = [
        lanePos(keys, keys - 1 - pos),
        lanePos(keys, pos + Math.ceil(keys / 2)),
        lanePos(keys, pos + 2),
      ].filter((lane) => lane !== note.lane);
      for (const other of options) {
        if (note.t - (lastUse.get(other) ?? -99) < 0.18) continue;
        const tooClose = taps.some((m) => m !== note && m.lane === other && m.t > note.t && m.t - note.t < 0.16);
        if (tooClose) continue;
        taps.push({ t: note.t, lane: other, step: 0, strong: true, barNo: note.barNo, chord: true });
        lastUse.set(other, note.t);
        chords++;
        break;
      }
    }
  }

  taps.sort((a, b) => a.t - b.t || a.lane - b.lane);
  return taps;
}

// ---------------------------------------------------------------- holds
function addHolds(song, sec, taps) {
  if (sec.keys < 4 || sec.energy > 0.78 || sec.end - sec.start < 5) return;
  const { beat } = tempoFor(song, sec);
  const byLane = new Map();
  for (const note of taps) {
    if (!byLane.has(note.lane)) byLane.set(note.lane, []);
    byLane.get(note.lane).push(note);
  }
  const gaps = [];
  for (const [lane, list] of byLane) {
    list.sort((a, b) => a.t - b.t);
    for (let i = 0; i < list.length - 1; i++) {
      const gap = list[i + 1].t - list[i].t;
      if (gap < 1.12) continue;
      gaps.push({ note: list[i], lane, gap });
    }
  }
  gaps.sort((a, b) => b.gap - a.gap);
  const limit = sec.holds ?? (sec.energy < 0.45 ? 3 : 2);
  let added = 0;
  for (const entry of gaps) {
    if (added >= limit) break;
    if (entry.note.type === 'hold') continue;
    const dur = Math.min(beat * 2, entry.gap - 0.22);
    if (dur < 0.55) continue;
    entry.note.type = 'hold';
    entry.note.dur = round(dur);
    added++;
  }
}

// ---------------------------------------------------------------- events
function barEnergy(analysis, sec, t, bar, medianPeaks, peakIndex) {
  if (analysis.bars?.length) {
    const idx = lowerBound(analysis.bars, t + 0.01);
    const barData = analysis.bars[Math.max(0, Math.min(analysis.bars.length - 1, idx - 1))];
    if (barData && Math.abs(barData.t - t) < bar * 1.1) return clamp(barData.rel, 0.2, 1.55);
  }
  const count = peakIndex.filter((p) => p.t >= t && p.t < t + bar).length;
  return clamp(0.3 + (count / (medianPeaks * Math.max(0.65, sec.energy + 0.55))) * 0.6, 0.2, 1.5);
}

function buildAccentEvents(track, song, sections, taps, analysis) {
  const events = [];
  const allPeaks = analysis.peaks;
  const medianPeaks = Math.max(1, allPeaks.length / Math.max(1, song.duration / 2));
  const theme = song.theme || '';
  const intention = theme === 'intention';

  for (const sec of sections) {
    if (!playableSection(track, sec) && !sec.intro) continue;
    const { beat, bar, offset } = tempoFor(song, sec);
    const idle = idleLanes(sec.keys);
    const firstBar = Math.ceil((sec.start - offset) / bar - 1e-9);
    const lastBar = Math.ceil((sec.end - offset) / bar - 1e-9);
    const sectionTaps = taps.filter((n) => n.t >= sec.start && n.t < sec.end);

    for (let barNo = firstBar, i = 0; barNo < lastBar; barNo++, i++) {
      const t = offset + barNo * bar;
      if (t < sec.start - 0.02 || t >= sec.end - 0.03) continue;
      const rel = barEnergy(analysis, sec, t, bar, medianPeaks, allPeaks);
      const pulse = round(clamp(0.18 + rel * 0.58, 0.2, 1.2), 2);
      events.push({ t: round(t), type: 'pulse', power: pulse });

      if (!intention && idle.length && i % 2 === 0) {
        const lane = idle[(i / 2) % idle.length];
        events.push({
          t: round(t + 0.02), type: 'echo', lane,
          dir: lane < 3.5 ? -1 : 1,
          power: round(clamp(0.4 + rel * 0.6, 0.4, 1.3), 2),
        });
      }

      if (!intention && sec.energy > 0.6 && i % 4 === 2 && sectionTaps.length) {
        const target = sectionTaps.reduce((best, n) =>
          Math.abs(n.t - (t + beat)) < Math.abs(best.t - (t + beat)) ? n : best, sectionTaps[0]);
        events.push({
          t: round(t + beat), type: 'burst', lane: target.lane,
          power: round(clamp(0.45 + rel * 0.62, 0.5, 1.25), 2),
        });
      }
      if (rel > 1.24 && i > 0) {
        const prev = barEnergy(analysis, sec, t - bar, bar, medianPeaks, allPeaks);
        if (prev < 1.06) {
          events.push({ t: round(t + 0.01), type: 'vibe', power: round(clamp(rel * 0.72, 0.5, 1.15), 2) });
        }
      }
    }

    if (sec.energy > 0.82 && (sec.end - sec.start) > 6) {
      events.push({ t: round(sec.start + 0.02), type: 'vibe', power: round(clamp(sec.energy * 0.8, 0.5, 1.15), 2) });
    }
    if (!intention && sec.energy > 0.76 && sec.motion) {
      events.push({
        t: round(sec.start + 0.03), type: 'motion', style: sec.motion,
        amp: sec.motionAmp, speed: sec.motionSpeed, pitch: sec.motionPitch,
      });
    }
  }
  return events;
}

function buildGhosts(track, song, sections) {
  if (song.theme === 'intention') return [];
  const ghosts = [];
  for (const sec of sections) {
    const idle = idleLanes(sec.keys);
    if (!idle.length) continue;
    const { bar } = tempoFor(song, sec);
    idle.forEach((lane, i) => {
      ghosts.push({ t: round(sec.start + 0.04 + i * 0.055), lane, type: 'sweep' });
      const bounce = sec.start + bar * 2 + i * 0.12;
      if (bounce < sec.end - 0.1) ghosts.push({ t: round(bounce), lane, type: 'bounce' });
    });
  }
  return ghosts.sort((a, b) => a.t - b.t);
}

// ---------------------------------------------------------------- assemble
function finalizeNotes(track, sections, taps) {
  const holdLane = new Map();
  const notes = [];
  for (const note of taps) {
    if (note.t < track.minFirstNote) continue;
    notes.push(note.type === 'hold'
      ? { t: round(note.t), lane: note.lane, type: 'hold', dur: round(note.dur) }
      : { t: round(note.t), lane: note.lane });
  }
  notes.sort((a, b) => a.t - b.t || a.lane - b.lane);
  for (const note of notes) {
    if (note.type === 'hold') {
      if (!holdLane.has(note.lane)) holdLane.set(note.lane, []);
      holdLane.get(note.lane).push(note);
    }
  }
  return notes;
}

function validate(track, chart) {
  const errors = [];
  const sections = chart.sections;
  const song = chart.song;
  let prevT = -Infinity;
  const lastByLane = new Map();
  for (const note of chart.notes) {
    if (!Number.isFinite(note.t) || !Number.isFinite(note.lane)) errors.push(`bad note ${JSON.stringify(note)}`);
    if (note.t < prevT - 1e-6) errors.push(`notes unsorted at ${note.t}`);
    prevT = note.t;
    if (note.t < 0 || note.t > song.chartEnd) errors.push(`note outside chart ${note.t}`);
    const sec = [...sections].reverse().find((s) => note.t >= s.start && note.t < s.end + 0.05);
    if (!sec) errors.push(`note without section ${note.t}`);
    else if (!ACTIVE[sec.keys]?.includes(note.lane)) errors.push(`lane ${note.lane} inactive in ${sec.name} at ${note.t}`);
    const last = lastByLane.get(note.lane);
    if (last && note.t - last.t < 0.06) errors.push(`lane ${note.lane} retrigger ${last.t}->${note.t}`);
    if (last?.type === 'hold' && note.t < last.t + last.dur + 0.05) errors.push(`note inside hold lane ${note.lane} at ${note.t}`);
    lastByLane.set(note.lane, note);
  }
  const first = chart.notes[0];
  if (!first || first.t < track.minFirstNote - 0.01) errors.push(`first note ${first?.t} before ${track.minFirstNote}`);
  for (const sec of sections) {
    if (!playableSection(track, sec)) continue;
    const count = chart.notes.filter((n) => n.t >= sec.start && n.t < sec.end).length;
    if (count === 0) errors.push(`playable section ${sec.name} has no notes`);
  }
  if (errors.length) throw new Error(`${chart.song.title}:\n${errors.slice(0, 20).join('\n')}`);
}

function buildChart(id) {
  const track = TRACKS[id];
  const map = SECTION_MAPS[id];
  const song = { ...map.song };
  const sections = map.sections;
  const analysis = readAnalysis(track.analysis);
  const rand = mulberry32(track.seed);
  const context = { lastLane: 3, lastT: -99 };
  const taps = [];

  for (const sec of sections) {
    if (!playableSection(track, sec)) continue;
    const candidates = buildCandidates(track, song, sec, analysis, rand);
    const assigned = assignLanes(track, song, sec, candidates, context);
    if (assigned.length) {
      const last = assigned[assigned.length - 1];
      context.lastLane = last.lane;
      context.lastT = last.t;
    }
    addHolds(song, sec, assigned);
    taps.push(...assigned);
  }

  const notes = finalizeNotes(track, sections, taps);
  const accents = buildAccentEvents(track, song, sections, notes, analysis);
  const gimmick = GIMMICKS[id] || { events: [], swings: [] };
  const seen = new Set();
  const accentsDeduped = accents.filter((ev) => {
    if (!Number.isFinite(ev.t)) return false;
    const key = `${ev.t}|${ev.type}|${ev.lane ?? ''}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  // Gimmick events are copied verbatim: several HUD/guilt cues intentionally
  // share a timestamp (for example, a cut to black plus a guilt bar reveal).
  const events = [...(gimmick.events || []), ...accentsDeduped]
    .filter((ev) => Number.isFinite(ev.t))
    .sort((a, b) => a.t - b.t);
  const ghosts = buildGhosts(track, song, sections);
  const chart = { song, sections, notes, events, ghosts };
  if (gimmick.swings?.length) chart.swings = gimmick.swings;

  validate(track, chart);

  const holds = notes.filter((n) => n.type === 'hold');
  const first = notes[0]?.t;
  const last = notes[notes.length - 1]?.t;
  console.log(
    `${id.padEnd(13)} ${String(notes.length).padStart(3)} notes · ${String(holds.length).padStart(2)} holds`
    + ` · ${String(events.length).padStart(3)} events · ${String(ghosts.length).padStart(2)} ghosts`
    + ` · ${first?.toFixed(2)}-${last?.toFixed(2)}s`,
  );

  fs.writeFileSync(path.join(CHART_DIR, `${id}.js`), `${HEADER}export const CHART = ${JSON.stringify(chart, null, 2)};\n`);
  return chart;
}

for (const id of Object.keys(TRACKS)) buildChart(id);

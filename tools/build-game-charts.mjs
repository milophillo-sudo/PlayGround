function tierFor(density) {
  if (density < 0.34) return 'sparse';
  if (density < 0.62) return 'groove';
  if (density < 0.82) return 'drive';
  return 'climax';
}

function tempoFor(song, sec) {
  const bpm = sec.bpm || song.bpm || 120;
  const beat = 60 / bpm;
  const bar = beat * 4;
  const offset = sec.beatOffset ?? song.beatOffset ?? 0;
  return { bpm, beat, bar, offset };
}

function playableSection(track, sec) {
  if (!sec || sec.notes === false) return false;
  if (sec.density === 0) return false;
  if (track.skipIntro && sec.intro) return false;
  if (/^OUTRO$/i.test(sec.name) && sec.end - sec.start < 10) return false;
  return sec.end - sec.start > 0.55 && sec.keys >= 1;
}

function gridStepFor(song, sec) {
  const { bpm } = tempoFor(song, sec);
  const density = sec.density ?? sec.energy;
  // Fast single-lane gimmicks stay on eighths; wide climaxes can use 16ths.
  if (sec.keys <= 2 || bpm > 170) return 2;
  if (density < 0.4) return 1;
  if (density < 0.8) return 2;
  return 4;
}

function buildCandidates(track, song, sec, analysis, rand) {
  const { beat, bar, offset } = tempoFor(song, sec);
  const density = clamp(sec.density ?? (0.16 + sec.energy * 0.86), 0, 1.15);
  const tier = tierFor(density);
  const cells = CELLS[tier];
  const div = gridStepFor(song, sec);
  const stride = div === 4 ? 1 : div === 2 ? 2 : 4;
  const used = new Set();
  const candidates = [];
  const firstBar = Math.floor((Math.max(sec.start, track.minFirstNote) - offset) / bar - 1e-9);
  const lastBar = Math.ceil((sec.end - offset) / bar - 1e-9);
  const snapWindow = clamp(beat * 0.16, 0.035, 0.075);

  for (let barNo = firstBar; barNo < lastBar; barNo++) {
    const barStart = offset + barNo * bar;
    if (barStart + bar < sec.start + 0.01) continue;
    if (barStart > sec.end - 0.12) continue;
    const barInPhrase = ((barNo % 4) + 4) % 4;
    const phrase = Math.floor(barNo / 4);
    const base = (track.seed + Math.floor(rand() * 4) + phrase * 3) % cells.length;
    const shape = [0, 0, 1, 3][barInPhrase];
    const cell = cells[(base + shape) % cells.length];

    for (let step = 0; step < 16; step += stride) {
      if (!cell[step]) continue;
      const gridT = barStart + (step * beat) / 4;
      if (gridT < sec.start + 0.01 || gridT > sec.end - 0.16) continue;
      if (gridT < track.minFirstNote) continue;

      const nearest = nearestPeak(analysis.peaks, gridT, snapWindow * 1.4, used);
      const onset = nearest ? nearest.peak.s : 0;
      const strong = step % 4 === 0;
      const offbeat = step % 2 !== 0;

      // Keep the skeleton on the grid; only let the record remove weak slots.
      if (!onset && !strong && rand() > 0.2 + density * 0.45) continue;
      if (!onset && offbeat && rand() > density * 0.6) continue;
      if (offbeat && density < 0.55 && rand() > 0.3) continue;

      let t = gridT;
      if (nearest && Math.abs(nearest.peak.t - gridT) <= snapWindow) {
        t = nearest.peak.t;
        used.add(nearest.index);
      }
      if (t < sec.start) t = gridT;
      if (t < sec.start || t > sec.end - 0.12) continue;

      const weight = (strong ? 1.15 : offbeat ? 0.45 : 0.8)
        + clamp(onset, 0, 2.2) * 0.75
        + (barInPhrase === 0 && step === 0 ? 0.55 : 0);
      candidates.push({
        t: round(t, 3), gridT: round(gridT, 3), step, barNo, barInPhrase,
        onset, weight, strong, offbeat,
      });
    }
  }

  // Phrase-aware density target: louder sections breathe faster, but the
  // target is a cap, not a promise, so quiet records stay sparse.
  const targetRate = sec.density != null
    ? 0.55 + clamp(sec.density, 0, 1) * 4.4
    : 0.8 + clamp(sec.energy, 0, 1.08) * 3.35;
  const desired = clamp(Math.round(targetRate * (sec.end - sec.start)), 2, 220);

  if (candidates.length > desired) {
    const removable = [...candidates].sort((a, b) =>
      (a.strong ? 1 : 0) - (b.strong ? 1 : 0) || a.weight - b.weight || b.t - a.t);
    const drop = new Set();
    for (const cand of removable) {
      if (candidates.length - drop.size <= desired) break;
      if (cand.step === 0) continue;
      drop.add(cand);
    }
    for (let i = candidates.length - 1; i >= 0; i--) {
      if (drop.has(candidates[i])) candidates.splice(i, 1);
    }
  } else if (candidates.length < desired) {
    const pool = analysis.peaks
      .map((peak, index) => ({ peak, index }))
      .filter(({ peak, index }) =>
        !used.has(index)
        && peak.t > Math.max(sec.start, track.minFirstNote) + 0.1
        && peak.t < sec.end - 0.2
        && peak.s > 0.55
        && !candidates.some((c) => Math.abs(c.t - peak.t) < 0.11));
    pool.sort((a, b) => b.peak.s - a.peak.s || a.peak.t - b.peak.t);
    for (const { peak, index } of pool) {
      if (candidates.length >= desired) break;
      used.add(index);
      candidates.push({
        t: round(peak.t, 3), gridT: round(peak.t, 3), step: 2,
        barNo: Math.floor((peak.t - offset) / bar),
        barInPhrase: ((Math.floor((peak.t - offset) / bar) % 4) + 4) % 4,
        onset: peak.s, weight: 0.5 + peak.s * 0.4, strong: false, offbeat: true,
      });
    }
  }

  candidates.sort((a, b) => a.t - b.t);
  const deduped = [];
  for (const cand of candidates) {
    const prev = deduped[deduped.length - 1];
    if (prev && Math.abs(prev.t - cand.t) < 0.032) {
      if (cand.weight > prev.weight) deduped[deduped.length - 1] = cand;
      continue;
    }
    deduped.push(cand);
  }
  return deduped;
}


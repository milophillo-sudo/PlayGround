// ---------------------------------------------------------------- helpers
function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const round = (n, d = 3) => +Number(n).toFixed(d);
const clamp = (n, a, b) => Math.max(a, Math.min(b, n));
const lanePos = (keys, pos) => ACTIVE[keys][((pos % keys) + keys) % keys];
const idleLanes = (keys) => ALL.filter((lane) => !ACTIVE[keys].includes(lane));

function median(values) {
  if (!values.length) return 1;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)] || 1;
}

function readAnalysis(name) {
  const raw = JSON.parse(fs.readFileSync(path.join(SOURCE, name), 'utf8'));
  const peaks = raw.peaks
    .map((p) => ({ t: p.t, s: p.s ?? p.strength ?? 0 }))
    .filter((p) => Number.isFinite(p.t) && Number.isFinite(p.s))
    .sort((a, b) => a.t - b.t);
  const scale = median(peaks.map((p) => p.s)) || 1;
  for (const peak of peaks) peak.s = clamp(peak.s / scale, 0.05, 3);
  const bars = raw.bars || [];
  const stats = raw.windows?.length
    ? null
    : bars.length
      ? bars
      : null;
  return { peaks, bars: stats, duration: raw.duration };
}

function lowerBound(list, t) {
  let lo = 0;
  let hi = list.length;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (list[mid].t < t) lo = mid + 1;
    else hi = mid;
  }
  return lo;
}

function nearestPeak(peaks, t, window, used = null) {
  let idx = lowerBound(peaks, t - window);
  let best = null;
  let bestDist = Infinity;
  for (; idx < peaks.length && peaks[idx].t <= t + window; idx++) {
    if (used && used.has(idx)) continue;
    const dist = Math.abs(peaks[idx].t - t);
    if (dist < bestDist) {
      best = { index: idx, peak: peaks[idx] };
      bestDist = dist;
    }
  }
  return best;
}

function peaksBetween(peaks, a, b) {
  const out = [];
  for (let i = lowerBound(peaks, a); i < peaks.length && peaks[i].t <= b; i++) out.push(peaks[i]);
  return out;
}


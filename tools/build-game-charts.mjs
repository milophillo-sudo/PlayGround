// Builds every playable chart with one shared method, while the authored
// section maps and the gimmick event scores stay untouched.
//
// The charting method is "phrase grammar over onset-locked slots":
//   1. every section gets a tempo grid and a four-bar phrase shape (A A' B C);
//   2. rhythmic cells are chosen from a groove library that follows section
//      energy, then thinned/supplemented against the decoded onsets so notes
//      land on the record instead of only on a metronome;
//   3. lanes are assigned with a playability pass (figure per bar, bounded
//      jumps, hand-safe repeats) and chords are reserved for phrase peaks;
//   4. long same-lane gaps become holds, so sustains follow the arrangement;
//   5. accent events are regenerated from bar energy, while boss/clock/guilt
//      events are copied verbatim from tools/source/gimmick-events.json.
//
// Run: node tools/build-game-charts.mjs
